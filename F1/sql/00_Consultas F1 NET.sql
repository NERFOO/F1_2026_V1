/*________________RESULT RACE________________*/
CREATE OR ALTER VIEW V_RESULTRACE 
AS
	SELECT RR.POSITION_RACE, RR.LAP_TIME, D.DRIVER_NAME, T.TEAM_NAME, RR.POINTS, RR.ID_RACE
	FROM TEAM T
	INNER JOIN DRIVER D ON T.ID_TEAM = D.ID_TEAM
	INNER JOIN RESULT_RACE RR ON D.ID_DRIVER = RR.ID_DRIVER
	INNER JOIN RACE R ON RR.ID_RACE = R.ID_RACE
GO

CREATE PROCEDURE SP_CREATE_RESULTRACE (@POSITION INT, @POINTS INT, @LAPTIME NVARCHAR(100), @IDRACE INT, @IDDRIVER INT)
AS
	INSERT INTO RESULT_RACE VALUES(@POSITION, @POINTS, @LAPTIME, @IDRACE, @IDDRIVER);
GO

CREATE PROCEDURE SP_FIND_RESULTRACE (@IDRACE INT)
AS
	SELECT RR.POSITION_RACE, RR.LAP_TIME, D.DRIVER_NAME, T.TEAM_NAME, RR.POINTS, R.ID_RACE FROM TEAM T
	INNER JOIN DRIVER D ON T.ID_TEAM = D.ID_TEAM
	INNER JOIN RESULT_RACE RR ON D.ID_DRIVER = RR.ID_DRIVER
	INNER JOIN RACE R ON RR.ID_RACE = R.ID_RACE
	WHERE RR.ID_RACE = @IDRACE
	ORDER BY RR.POSITION_RACE ASC
GO

