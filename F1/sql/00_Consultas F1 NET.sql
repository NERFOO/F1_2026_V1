GO

-- CREA UN NUEVO REGISTRO DE CARRERA
CREATE PROCEDURE SP_CREATE_RACE 
(@GPNAME NVARCHAR(100), @CIRCUITNAME NVARCHAR(100), @COUNTRY NVARCHAR(100), @GPDATESTART NVARCHAR(50), @GPDATEEND NVARCHAR(50), 
@GPLENGTH INT, @GPDISTANCE DECIMAL(6,3), @TURN INT, @LAP INT, @LASTWINNER NVARCHAR(50), @FASTLAP NVARCHAR(100))
AS
	INSERT INTO RACE 
	VALUES(@GPNAME, @CIRCUITNAME, @COUNTRY, @GPDATESTART, @GPDATEEND, @GPLENGTH, @GPDISTANCE, @TURN, @LAP, @LASTWINNER, @FASTLAP);
GO

-- ACTUALIZA UN REGISTRO DE CARRERA
CREATE PROCEDURE SP_UPDATE_RACE 
(@IDRACE INT, @GPNAME NVARCHAR(100), @CIRCUITNAME NVARCHAR(100), @COUNTRY NVARCHAR(100), @GPDATESTART NVARCHAR(50), @GPDATEEND NVARCHAR(50), 
@GPLENGTH INT, @GPDISTANCE DECIMAL(6,3), @TURN INT, @LAP INT, @LASTWINNER NVARCHAR(50), @FASTLAP NVARCHAR(100))
AS
	UPDATE RACE SET GP_NAME = @GPNAME, CIRCUIT_NAME = @CIRCUITNAME, COUNTRY = @COUNTRY, GP_DATE_START = @GPDATESTART,
	GP_DATE_END = @GPDATEEND, GP_LENGTH = @GPLENGTH,GP_DISTANCE = @GPDISTANCE, TURN = @TURN, LAP = @LAP, LAST_WINNER = @LASTWINNER, 
	FAST_LAP = @FASTLAP 
	WHERE ID_RACE = @IDRACE
GO



